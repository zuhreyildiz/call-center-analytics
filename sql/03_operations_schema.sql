CREATE TABLE IF NOT EXISTS fact_operations (
    call_id VARCHAR(50) PRIMARY KEY REFERENCES fact_calls(call_id),
    agent_name VARCHAR(100),
    call_date DATE,
    call_time TIME,
    topic VARCHAR(100),
    answered VARCHAR(5),
    resolved VARCHAR(5),
    team VARCHAR(100),
    queue VARCHAR(100),
    channel VARCHAR(30),
    wait_seconds INT,
    talk_seconds INT,
    satisfaction_rating DECIMAL(3,2),
    repeat_call VARCHAR(5),
    escalated VARCHAR(5),
    sentiment VARCHAR(30),
    sla_target_seconds INT,
    forecast_call_volume INT,
    required_staff INT,
    actual_staff INT,
    staffing_gap INT,
    loaded_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
